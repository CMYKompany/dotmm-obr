"""Bundle the per-letter content packs into the files the importer loads.

Sources (edit these, never the outputs):
  packs/content_{L}.json      Level 1 sub-map packs (rooms, secret doors, ...)
  packs/content_L2_{L}.json   Level 2 sub-map packs
  LEVELS below                per-level display name + field-confirmed origins
  packs/token_manifest.json   only its "note" field is used

Outputs (generated - do not hand-edit):
  packs/level<N>.json   {name, origins, packs} - fetched at runtime by
                        import.js when a file for that level is dropped
  content.js            TOKEN_MANIFEST only: every monster name across all
                        levels with total count and room refs, for token
                        matching. Rebuilt from the packs, so it can't drift.

Rerun after editing any source:

    python3 pipeline/build_packs.py
"""
import json
import os

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
PACKS = os.path.join(ROOT, "packs")

LEVELS = {
    "1": {
        "name": "Dungeon Level",
        "packfile": "content_{L}.json",
        # Field-confirmed origins (B/C corrections baked 2026-07-07).
        "origins": {"A": [0, 0], "B": [0, -43], "C": [65, -43],
                    "D": [0, 54], "E": [54, 25], "F": [41, 74]},
    },
    "2": {
        "name": "Arcane Chambers",
        "packfile": "content_L2_{L}.json",
        # Map-key registration, then field-confirmed corrections baked
        # 2026-07-14: B (+4,-2), C (+4,+2), D (0,+1), E (+4,+1), F (+5,+3).
        "origins": {"A": [0, 0], "B": [65, 0], "C": [20, 50],
                    "D": [0, 63], "E": [54, 96], "F": [1, 127]},
    },
}
LETTERS = "ABCDEFGHIJKLMNOPQRSTUVWXYZ"  # levels have varying sub-map counts


def dump(obj):
    return json.dumps(obj, indent=1, ensure_ascii=False)


tokens = {}  # monster name -> {name, total, rooms}
for level, meta in LEVELS.items():
    packs = {}
    for L in LETTERS:
        path = os.path.join(PACKS, meta["packfile"].format(L=L))
        if os.path.exists(path):
            with open(path, encoding="utf-8") as f:
                packs[L] = json.load(f)
    missing = [L for L in packs if L not in meta["origins"]]
    if missing:
        raise SystemExit(f"level {level}: no origin for map(s) {missing}")
    data = {
        "name": meta["name"],
        "origins": {k: v for k, v in meta["origins"].items() if k in packs},
        "packs": packs,
    }
    with open(os.path.join(PACKS, f"level{level}.json"), "w", encoding="utf-8") as f:
        f.write(dump(data) + "\n")
    for L, pack in packs.items():
        for room in pack["rooms"]:
            for mon in room["monsters"]:
                e = tokens.setdefault(mon["name"], {"name": mon["name"], "total": 0, "rooms": []})
                e["total"] += mon.get("count", 1)
                e["rooms"].append(f"{L}:{room['id']}")
    rooms = sum(len(p["rooms"]) for p in packs.values())
    print(f"level {level} ({meta['name']}): {len(packs)} maps, {rooms} rooms -> packs/level{level}.json")

with open(os.path.join(PACKS, "token_manifest.json"), encoding="utf-8") as f:
    note = json.load(f)["note"]
manifest = {"note": note, "monsters": sorted(tokens.values(), key=lambda m: m["name"])}
with open(os.path.join(ROOT, "content.js"), "w", encoding="utf-8") as f:
    f.write("// Generated by pipeline/build_packs.py - do not edit by hand.\n"
            "export const TOKEN_MANIFEST = " + dump(manifest) + ";\n")
print(f"content.js: {len(manifest['monsters'])} monsters")
